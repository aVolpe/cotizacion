-- Stores a row per price instead of a row per query.
--
-- The places are queried every 10 minutes and most of the time the rates don't change, so
-- query_response + query_response_detail had a row per query and currency (84M in production, 11 GB).
-- exchange_rate keeps one row per place/branch/currency while the purchase and sale prices don't change:
-- first_seen and last_seen are the first and last query that saw it, last_execution_id the last execution
-- (the API shows the rates of the last execution). No price is lost: the price of any query is the one
-- of the row whose [first_seen, last_seen] contains it.
--
-- What is not kept:
--  - the exact time of every query that repeated a price (the execution table still has every run),
--  - the trends (they can be derived from the previous price),
--  - full_data (always null),
--  - the second rate of a currency repeated in the same query (old gatherer bugs: Mercosur USD with sale 0
--    until 2025-07, MyD UYU in 2019), the first one is kept.
--
-- The production database also has old_query_response_detail and old2_query_response_detail, details of
-- 2018-05-17 to 2018-08-07 moved out of query_response_detail by hand (their queries have no other detail
-- for those currencies). They are part of the history, so they are migrated too and then dropped.
--
-- The new table is built in a single sorted pass (gaps and islands), then the old tables are dropped.

SET LOCAL work_mem = '256MB';

CREATE TABLE exchange_rate
(
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id          bigint    NOT NULL REFERENCES place (id),
    -- null when the place is queried as a whole (most banks)
    branch_id         bigint REFERENCES place_branch (id),
    iso_code          text      NOT NULL,
    purchase_price    bigint    NOT NULL,
    sale_price        bigint    NOT NULL,
    first_seen        timestamp NOT NULL,
    last_seen         timestamp NOT NULL,
    -- null for the rates last seen before the executions existed (2018)
    last_execution_id bigint REFERENCES execution (id),
    -- the newest row of each place/branch/currency, the one a new query is compared with
    latest            boolean   NOT NULL DEFAULT false,
    CONSTRAINT exchange_rate_seen_check CHECK (first_seen <= last_seen)
);


-- Every detail to migrate, including the old_* tables when they exist (only in production).
DO
$$
    DECLARE
        v_sql text := 'SELECT id, query_response_id, iso_code, purchase_price, sale_price FROM query_response_detail';
        v_old text;
    BEGIN
        FOREACH v_old IN ARRAY ARRAY ['old_query_response_detail', 'old2_query_response_detail']
            LOOP
                IF to_regclass(v_old) IS NOT NULL THEN
                    v_sql := v_sql || ' UNION ALL SELECT id, query_response_id, iso_code, purchase_price, sale_price FROM '
                                 || v_old;
                END IF;
            END LOOP;
        EXECUTE 'CREATE TEMPORARY VIEW detail_to_migrate AS ' || v_sql;
    END
$$;


INSERT INTO exchange_rate (place_id, branch_id, iso_code, purchase_price, sale_price, first_seen, last_seen,
                           last_execution_id, latest)
WITH detail AS (
    SELECT qr.place_id,
           qr.branch_id,
           d.iso_code,
           d.purchase_price,
           d.sale_price,
           qr.date,
           qr.execution_id,
           qr.id             AS query_id,
           d.id              AS detail_id,
           -- the same currency twice in a query: only the first one is kept
           lag(qr.id) OVER w AS previous_query_id
    FROM query_response qr
             JOIN detail_to_migrate d ON d.query_response_id = qr.id
    WHERE d.iso_code IS NOT NULL
      AND d.purchase_price IS NOT NULL
      AND d.sale_price IS NOT NULL
      AND qr.place_id IS NOT NULL
      AND qr.date IS NOT NULL
    WINDOW w AS (PARTITION BY qr.place_id, qr.branch_id, d.iso_code ORDER BY qr.date, qr.id, d.id)),
     observation AS (
         -- a price starts a new row when it differs from the previous query of the same place/branch/currency
         SELECT *,
                CASE
                    WHEN purchase_price = lag(purchase_price) OVER w
                        AND sale_price = lag(sale_price) OVER w THEN 0
                    ELSE 1 END AS starts
         FROM detail
         WHERE previous_query_id IS DISTINCT FROM query_id
         WINDOW w AS (PARTITION BY place_id, branch_id, iso_code ORDER BY date, query_id, detail_id)),
     island AS (
         SELECT *,
                sum(starts) OVER (PARTITION BY place_id, branch_id, iso_code ORDER BY date, query_id, detail_id
                    ROWS UNBOUNDED PRECEDING) AS island
         FROM observation),
     rate AS (
         SELECT place_id,
                branch_id,
                iso_code,
                island,
                min(purchase_price) AS purchase_price,
                min(sale_price)     AS sale_price,
                min(date)           AS first_seen,
                max(date)           AS last_seen,
                -- the execution ids grow with the time
                max(execution_id)   AS last_execution_id
         FROM island
         GROUP BY place_id, branch_id, iso_code, island)
SELECT place_id,
       branch_id,
       iso_code,
       purchase_price,
       sale_price,
       first_seen,
       last_seen,
       last_execution_id,
       island = max(island) OVER (PARTITION BY place_id, branch_id, iso_code)
FROM rate
ORDER BY first_seen, place_id, branch_id, iso_code;


DROP VIEW detail_to_migrate;
DROP TABLE IF EXISTS old_query_response_detail;
DROP TABLE IF EXISTS old2_query_response_detail;
DROP TABLE query_response_detail;
DROP TABLE query_response;


CREATE UNIQUE INDEX exchange_rate_latest_key ON exchange_rate (place_id, coalesce(branch_id, -1), iso_code) WHERE latest;
-- the latest rates of a currency (ExchangeRateRepository.getMaxByPlaceInISO)
CREATE INDEX exchange_rate_latest_iso_idx ON exchange_rate (iso_code, last_execution_id) WHERE latest;
-- the history of a currency, for the charts
CREATE INDEX exchange_rate_iso_first_seen_idx ON exchange_rate (iso_code, first_seen);

ANALYZE exchange_rate;
